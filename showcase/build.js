// `bun showcase/build.js` writes the static showcase to showcase/dist;
// `--watch` serves it and recompiles the Elm on change.
//
// It first generates src/Generated/Sources.elm with the source of every story
// function, so the code shown under a story is the code that renders it.

import { watch } from "node:fs";
import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

const here = import.meta.dir;
const storiesDir = path.join(here, "src/Stories");
const generated = path.join(here, "src/Generated/Sources.elm");
const elmOut = path.join(here, "elm-stuff/showcase.js");

// Served as-is next to the bundle: published path -> source. The CSS is
// found by module resolution, so it works wherever bun installed it.
const resolve = (specifier) => {
  try {
    return Bun.resolveSync(specifier, here);
  } catch {
    console.error(`showcase: can't find ${specifier}. Run \`bun install\` in designsystem/.`);
    process.exit(1);
  }
};
const staticFiles = {
  "vendor/designsystemet.css": resolve("@digdir/designsystemet-css"),
  "vendor/theme.css": resolve("@digdir/designsystemet-css/theme"),
  "showcase.css": path.join(here, "showcase.css"),
};
const staticDirs = { assets: path.join(here, "assets") };

const lowerFirst = (s) => s.charAt(0).toLowerCase() + s.slice(1);
const elmString = (s) =>
  '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n") + '"';

// Top-level declarations in an elm-formatted module: they start in column 0
// and run until the next line that starts in column 0 with something else.
function declarations(source) {
  const decls = new Map();
  const lines = source.split("\n");
  let current = null;
  for (const line of lines) {
    const start = /^([a-z][A-Za-z0-9_]*)( :| .*=$| =$)/.exec(line);
    if (start) {
      // An annotation and its definition belong to the same declaration.
      if (current?.name !== start[1]) {
        current = { name: start[1], lines: [] };
        decls.set(current.name, current);
      }
    } else if (line !== "" && !/^\s/.test(line)) {
      current = null;
    }
    if (current) current.lines.push(line);
  }
  return new Map(
    [...decls].map(([name, d]) => [name, d.lines.join("\n").trimEnd()]),
  );
}

async function generateSources() {
  const files = (await readdir(storiesDir)).filter((f) => f.endsWith(".elm"));
  const entries = [];
  const problems = [];
  for (const file of files.sort()) {
    const source = await readFile(path.join(storiesDir, file), "utf8");
    const module_ = /^module ([\w.]+)/m.exec(source)?.[1];
    const decls = declarations(source);
    for (const [, name, fn] of source.matchAll(/Story\.story\s+"(\w+)"\s+(?:\(\s*)?([a-z]\w*)/g)) {
      if (fn !== lowerFirst(name)) {
        problems.push(`${file}: story "${name}" should be defined as \`${lowerFirst(name)}\`, not \`${fn}\``);
      } else if (!decls.has(fn)) {
        problems.push(`${file}: no top-level \`${fn}\` for story "${name}"`);
      } else {
        entries.push([module_, fn, decls.get(fn)]);
      }
    }
  }
  if (problems.length) throw new Error(problems.join("\n"));

  const cases = entries
    .map(([m, fn, src]) => `        ( ${elmString(m)}, ${elmString(fn)} ) ->\n            Just ${elmString(src)}\n`)
    .join("\n");
  const elm = `module Generated.Sources exposing (get)

{-| Generated by showcase/build.js. Do not edit.
-}


get : String -> String -> Maybe String
get module_ name =
    case ( module_, name ) of
${cases}
        _ ->
            Nothing
`;
  await mkdir(path.dirname(generated), { recursive: true });
  await writeFile(generated, elm);
  return entries.length;
}

async function compileElm(optimize) {
  const count = await generateSources();
  const args = ["elm", "make", "src/Main.elm", `--output=${elmOut}`];
  if (optimize) args.push("--optimize");
  const make = Bun.spawn(["bunx", ...args], { cwd: here, stdout: "inherit", stderr: "inherit" });
  const ok = (await make.exited) === 0;
  if (ok) console.log(`showcase: compiled ${count} stories`);
  return ok;
}

if (process.argv.includes("--generate-only")) {
  // For tools that read the showcase sources (elm-review), without compiling.
  await generateSources();
} else if (process.argv.includes("--watch")) {
  await compileElm(false);
  const { default: index } = await import("./index.html");
  const server = Bun.serve({
    port: Number(process.env.PORT || 5174),
    hostname: "0.0.0.0",
    development: true,
    routes: {
      ...Object.fromEntries(
        Object.entries(staticFiles).map(([url, file]) => [`/${url}`, () => new Response(Bun.file(file))]),
      ),
      "/assets/:file": (req) => new Response(Bun.file(path.join(staticDirs.assets, req.params.file))),
      "/*": index,
    },
  });
  let pending = null;
  const rebuild = (_, file) => {
    if (!file?.endsWith(".elm") || file.includes("Generated")) return;
    clearTimeout(pending);
    pending = setTimeout(() => compileElm(false), 50);
  };
  watch(path.join(here, "src"), { recursive: true }, rebuild);
  watch(path.join(here, "../src"), { recursive: true }, rebuild);
  console.log(`showcase: ${server.url} (reload the page after a rebuild)`);
} else {
  if (!(await compileElm(true))) process.exit(1);
  await rm(path.join(here, "dist"), { recursive: true, force: true });
  const result = await Bun.build({
    entrypoints: [path.join(here, "index.html")],
    outdir: path.join(here, "dist"),
    minify: true,
    publicPath: process.env.SHOWCASE_BASE_URL || "./",
  });
  if (!result.success) {
    console.error(result.logs);
    process.exit(1);
  }
  for (const [url, file] of Object.entries(staticFiles)) {
    await cp(file, path.join(here, "dist", url));
  }
  for (const [url, dir] of Object.entries(staticDirs)) {
    await cp(dir, path.join(here, "dist", url), { recursive: true });
  }
  console.log("showcase: built to showcase/dist");
}
